// @vitest-environment jsdom
import { it, expect, vi, afterEach } from 'vitest';
import { render, screen, fireEvent, act, within } from '@testing-library/react';
import { tools } from '../../src/features/tools/catalog.js';
import ToolCard from '../../src/features/tools/ToolCard.jsx';
import ToolWorkspace from '../../src/features/tools/ToolWorkspace.jsx';

afterEach(() => vi.unstubAllGlobals());
it('invalidates late asynchronous results and copy on any input change', async () => {
    let resolve;
    vi.stubGlobal('crypto',{subtle:{digest:()=>new Promise(done=>{resolve=done;})}});
    render(<ToolCard definition={tools.find(t=>t.id==='sha256')} />);
    fireEvent.change(screen.getByLabelText('Input text'),{target:{value:'old'}});
    fireEvent.click(screen.getByRole('button',{name:'Hash'}));
    expect(screen.getByRole('status')).toHaveTextContent('Processing');
    fireEvent.change(screen.getByLabelText('Input text'),{target:{value:'new'}});
    await act(async()=>resolve(new Uint8Array([1,2]).buffer));
    expect(screen.getByLabelText('Result SHA-256')).toHaveTextContent('No result yet');
    expect(screen.getByRole('button',{name:'Copy'})).toBeDisabled();
});
it('renders markup as text, announces errors, handles denied clipboard and empty output', async () => {
    vi.stubGlobal('navigator',{clipboard:{writeText:vi.fn().mockRejectedValue(new Error('denied'))}});
    render(<ToolCard definition={tools.find(t=>t.id==='html')} />);
    const input=screen.getByLabelText('Input text');
    fireEvent.change(input,{target:{value:'&lt;img src=x onerror=alert(1)&gt;'}});
    fireEvent.click(screen.getByRole('button',{name:'Decode'}));
    expect(await screen.findByText('<img src=x onerror=alert(1)>')).toBeVisible();
    expect(document.querySelector('img')).toBeNull();
    fireEvent.click(screen.getByRole('button',{name:'Copy'}));
    expect(await screen.findByRole('alert')).toHaveTextContent('Select the result');
    fireEvent.change(input,{target:{value:'&unknown;'}});
    fireEvent.click(screen.getByRole('button',{name:'Decode'}));
    expect(await screen.findByRole('alert')).toHaveTextContent('Invalid input');
    expect(screen.getByRole('button',{name:'Copy'})).toBeDisabled();
    fireEvent.change(input,{target:{value:''}});
    fireEvent.click(screen.getByRole('button',{name:'Encode'}));
    expect(await screen.findByText('Empty result')).toBeVisible();
    expect(screen.getByRole('button',{name:'Copy'})).toBeDisabled();
});
it('uses password HMAC keys and invalidates late key-dependent work on key change', async () => {
    let resolve;
    vi.stubGlobal('crypto',{subtle:{importKey:async()=>({}),sign:()=>new Promise(done=>{resolve=done;})}});
    render(<ToolCard definition={tools.find(t=>t.id==='hmac256')} />);
    expect(screen.getByLabelText('HMAC key (UTF-8)')).toHaveAttribute('type','password');
    expect(screen.getByLabelText('HMAC key (UTF-8)')).toHaveAttribute('maxLength','1000');
    fireEvent.change(screen.getByLabelText('HMAC key (UTF-8)'),{target:{value:'first-key'}});
    await act(async()=>fireEvent.click(screen.getByRole('button',{name:'Compute HMAC'})));
    fireEvent.change(screen.getByLabelText('HMAC key (UTF-8)'),{target:{value:'second-key'}});
    await act(async()=>resolve(new Uint8Array([1]).buffer));
    expect(screen.getByLabelText('Result HMAC-SHA256')).toHaveTextContent('No result yet');
    expect(screen.getByRole('button',{name:'Copy'})).toBeDisabled();
});
it('clears generated output when a numeric option changes and announces its invalid range', async () => {
    render(<ToolCard definition={tools.find(t=>t.id==='digits')} />);
    fireEvent.click(screen.getByRole('button',{name:'Generate'}));
    expect(await screen.findByRole('button',{name:'Copy'})).toBeEnabled();
    fireEvent.change(screen.getByLabelText('Digits · 1–256'),{target:{value:'257'}});
    expect(screen.getByLabelText('Result Random digits')).toHaveTextContent('No result yet');
    expect(screen.getByRole('button',{name:'Copy'})).toBeDisabled();
    fireEvent.click(screen.getByRole('button',{name:'Generate'}));
    expect(await screen.findByRole('alert')).toHaveTextContent('between 1 and 256');
});
it('ignores clipboard success after editing and async failure after unmount', async () => {
    let finishCopy;
    vi.stubGlobal('navigator',{clipboard:{writeText:()=>new Promise(done=>{finishCopy=done;})}});
    const view=render(<ToolCard definition={tools.find(t=>t.id==='rot13')} />);
    fireEvent.change(screen.getByLabelText('Input text'),{target:{value:'abc'}});
    await act(async()=>fireEvent.click(screen.getByRole('button',{name:'Convert'})));
    fireEvent.click(screen.getByRole('button',{name:'Copy'}));
    fireEvent.change(screen.getByLabelText('Input text'),{target:{value:'def'}});
    await act(async()=>finishCopy());
    expect(screen.getByRole('status')).not.toHaveTextContent('Copied');
    view.unmount();
    let reject;
    vi.stubGlobal('crypto',{subtle:{digest:()=>new Promise((_,fail)=>{reject=fail;})}});
    const pending=render(<ToolCard definition={tools.find(t=>t.id==='sha256')} />);
    fireEvent.click(screen.getByRole('button',{name:'Hash'}));
    pending.unmount();
    await act(async()=>reject(new Error('old failure')));
    expect(screen.queryByRole('alert')).toBeNull();
});
it('filters all 22 stable cards by case/accent-insensitive search and category', async () => {
    render(<ToolWorkspace />);
    expect(screen.getAllByRole('article')).toHaveLength(22);
    const input=screen.getByLabelText('Search tools');
    fireEvent.change(input,{target:{value:'rándom dígits'}});
    expect(screen.getAllByRole('article')).toHaveLength(1);
    expect(within(screen.getByRole('article')).getByRole('heading')).toHaveTextContent('Random digits');
    fireEvent.change(input,{target:{value:''}});
    fireEvent.change(screen.getByLabelText('Category'),{target:{value:'hash'}});
    expect(screen.getAllByRole('article')).toHaveLength(4);
    fireEvent.change(input,{target:{value:'not-a-tool'}});
    expect(screen.queryAllByRole('article')).toHaveLength(0);
    expect(screen.getByText('No tools found')).toBeVisible();
});
it('reset restores numeric defaults and clears results and errors for its own card', async () => {
    render(<ToolCard definition={tools.find(t => t.id === 'digits')} />);
    const digits = screen.getByLabelText('Digits · 1–256');
    fireEvent.change(digits, { target: { value: '8' } });
    fireEvent.click(screen.getByRole('button', { name: 'Generate' }));
    expect(await screen.findByRole('button', { name: 'Copy' })).toBeEnabled();
    fireEvent.click(screen.getByRole('button', { name: 'Reset' }));
    expect(digits).toHaveValue(16);
    expect(screen.getByLabelText('Result Random digits')).toHaveTextContent('No result yet');
    expect(screen.getByRole('button', { name: 'Copy' })).toBeDisabled();
    fireEvent.change(digits, { target: { value: '257' } });
    fireEvent.click(screen.getByRole('button', { name: 'Generate' }));
    expect(await screen.findByRole('alert')).toBeVisible();
    fireEvent.click(screen.getByRole('button', { name: 'Reset' }));
    expect(screen.queryByRole('alert')).toBeNull();
});
it('reset clears text and HMAC key and retires a pending result', async () => {
    let resolve;
    vi.stubGlobal('crypto', { subtle: { importKey: async () => ({}), sign: () => new Promise(done => { resolve = done; }) } });
    render(<ToolCard definition={tools.find(t => t.id === 'hmac256')} />);
    fireEvent.change(screen.getByLabelText('Input text'), { target: { value: 'message' } });
    fireEvent.change(screen.getByLabelText('HMAC key (UTF-8)'), { target: { value: 'test-key' } });
    await act(async () => fireEvent.click(screen.getByRole('button', { name: 'Compute HMAC' })));
    expect(screen.getByRole('status')).toHaveTextContent('Processing');
    fireEvent.click(screen.getByRole('button', { name: 'Reset' }));
    expect(screen.getByLabelText('Input text')).toHaveValue('');
    expect(screen.getByLabelText('HMAC key (UTF-8)')).toHaveValue('');
    await act(async () => resolve(new Uint8Array([1]).buffer));
    expect(screen.getByLabelText('Result HMAC-SHA256')).toHaveTextContent('No result yet');
    expect(screen.getByRole('status')).toBeEmptyDOMElement();
    expect(screen.getByRole('button', { name: 'Copy' })).toBeDisabled();
    expect(screen.getByRole('button', { name: 'Compute HMAC' })).toBeEnabled();
});
it('reset ignores a late clipboard completion', async () => {
    let finish;
    vi.stubGlobal('navigator', { clipboard: { writeText: () => new Promise(done => { finish = done; }) } });
    render(<ToolCard definition={tools.find(t => t.id === 'rot13')} />);
    fireEvent.change(screen.getByLabelText('Input text'), { target: { value: 'abc' } });
    await act(async () => fireEvent.click(screen.getByRole('button', { name: 'Convert' })));
    fireEvent.click(screen.getByRole('button', { name: 'Copy' }));
    fireEvent.click(screen.getByRole('button', { name: 'Reset' }));
    await act(async () => finish());
    expect(screen.getByRole('status')).toBeEmptyDOMElement();
    expect(screen.getByLabelText('Input text')).toHaveValue('');
});
